"""Draws the Burrow mark (three nested arches, a burrow: burrow-icon.zip, 2026-11-08) into every file that
shows it, from one geometry, each centred exactly on its canvas (as Weft's tools/weft_mark.py).

The mark's box (strokes included) is 258 x 194 in the 512 design space, centred on (256, 256): the
zip's translate(0 -12) is baked into the paths below. Its launcher copy was 2.3 units above the
middle of the 108 canvas; here every copy is centred on the box.

  launcher  app/src/main/res/drawable/ic_launcher_foreground.xml   44 dp wide of the 108 dp canvas (the
                                                                   old mark's size), white on #A3294A
            app/src/main/res/drawable/ic_launcher_monochrome.xml   the same, for themed icons (Android 13+)
            app/src/main/res/values/colors.xml                     ic_launcher_background
  in app    app/src/main/res/drawable/ic_notification.xml          20 of 24 units, white: the notification
                                                                   small icon, and tinted in BurrowLogo
                                                                   (Welcome, About), the widget and the tile
  store     release/icon-512.png (+ fastlane icon.png, design/logo/play-store-icon-512.png): full square,
            Play masks it; the mark takes the launcher's share of what shows (44 of 72 dp → 313 px)
            release/feature-graphic-1024x500.png (+ fastlane featureGraphic.png, design/logo/)
  design    design/logo/*.svg, burrow-icon-512.png (rounded tile), burrow-wordmark.png

usage: python3 tools/burrow_mark.py        (PNGs are drawn with headless Chrome, as Weft's icon-512)
"""
import os
import shutil
import subprocess
import tempfile

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
BURGUNDY = "#A3294A"      # the logo's tile (burrow-icon.zip)
DEEP = "#791D37"          # the mark on the pale tile (feature graphic)
PALE = "#FCD4DE"          # the feature graphic's tile
INK = "#20181A"           # the wordmark's text
STROKE = 26               # in the 512 design space
BOX_W, BOX_H = 258, 194   # the mark's box, strokes included; centred on (256, 256)
PATHS = [
    "M140,340 V288 A116,116 0 0,1 372,288 V340",
    "M140,288 A76,76 0 0,1 292,288 V340",
    "M140,288 A36,36 0 0,1 212,288 V340",
]
LAUNCHER_DP = 44          # mark width on the 108 dp launcher canvas
STORE_PX = round(LAUNCHER_DP / 72 * 512)  # 72 dp of the 108 show inside the launcher mask
CHROME = "/Applications/Google Chrome.app/Contents/MacOS/Google Chrome"
FONT = os.path.join(ROOT, "app", "src", "main", "res", "font", "lexend.ttf")


def group(canvas, mark):
    """Scale and offset that put the mark, `mark` wide, in the middle of a `canvas` square."""
    s = mark / BOX_W
    return s, canvas / 2 - 256 * s


def vector(canvas_dp, viewport, mark, color, comment):
    s, t = group(viewport, mark)
    paths = "\n".join(
        f'        <path android:pathData="{d}" android:strokeColor="{color}" android:strokeWidth="{STROKE}" '
        f'android:strokeLineCap="round" android:strokeLineJoin="round" />' for d in PATHS)
    return f'''<?xml version="1.0" encoding="utf-8"?>
<!-- {comment}
     Generated by tools/burrow_mark.py: edit the geometry there. -->
<vector xmlns:android="http://schemas.android.com/apk/res/android"
    android:width="{canvas_dp}dp" android:height="{canvas_dp}dp"
    android:viewportWidth="{viewport}" android:viewportHeight="{viewport}">
    <group android:scaleX="{s:.5f}" android:scaleY="{s:.5f}" android:translateX="{t:.4f}" android:translateY="{t:.4f}">
{paths}
    </group>
</vector>
'''


def mark_svg(color, s=1.0, tx=0.0, ty=0.0):
    paths = "".join(f'<path d="{d}"/>' for d in PATHS)
    return (f'<g transform="translate({tx:.3f} {ty:.3f}) scale({s:.5f})" fill="none" stroke="{color}" '
            f'stroke-width="{STROKE}" stroke-linecap="round" stroke-linejoin="round">{paths}</g>')


def tile_svg(size, mark, radius, bg, fg):
    s, t = group(size, mark)
    rect = f'<rect width="{size}" height="{size}"' + (f' rx="{radius}"' if radius else "") + f' fill="{bg}"/>'
    return (f'<svg xmlns="http://www.w3.org/2000/svg" width="{size}" height="{size}" viewBox="0 0 {size} {size}">\n'
            f'  <!-- The Burrow mark (burrow-icon.zip, 2026-11-08), centred. Generated by tools/burrow_mark.py. -->\n'
            f'  {rect}\n  {mark_svg(fg, s, t, t)}\n</svg>\n')


def bare_svg(color):
    """The mark alone, its viewBox the mark's box (for docs and other artwork)."""
    x, y = 256 - BOX_W / 2, 256 - BOX_H / 2
    return (f'<svg xmlns="http://www.w3.org/2000/svg" viewBox="{x:g} {y:g} {BOX_W} {BOX_H}">\n'
            f'  <!-- Generated by tools/burrow_mark.py. -->\n  {mark_svg(color)}\n</svg>\n')


def write(rel, text):
    with open(os.path.join(ROOT, rel), "w") as f:
        f.write(text)
    print(rel)


def render(html, width, height, out, transparent=False):
    """Draws an HTML page to a PNG with headless Chrome."""
    with tempfile.TemporaryDirectory() as tmp:
        page = os.path.join(tmp, "page.html")
        with open(page, "w") as f:
            f.write(html)
        png = os.path.join(tmp, "shot.png")
        args = [CHROME, "--headless=new", "--disable-gpu", "--hide-scrollbars", "--force-device-scale-factor=1",
                f"--window-size={width},{height}", f"--screenshot={png}"]
        if transparent:
            args.append("--default-background-color=00000000")
        subprocess.run(args + ["file://" + page], check=True, capture_output=True)
        shutil.copy(png, os.path.join(ROOT, out))
    print(out)


def page(body, width, height):
    return f'''<!doctype html><html><head><meta charset="utf-8"><style>
@font-face {{ font-family: Lexend; src: url("file://{FONT}"); }}
html, body {{ margin: 0; width: {width}px; height: {height}px; overflow: hidden; background: transparent; }}
</style></head><body>{body}</body></html>'''


def feature_graphic():
    """1024 x 500: the pale tile with the mark, "Burrow" and two lines, on burgundy (the old layout)."""
    tile = 200
    s, t = group(tile, round(tile * 0.56))
    svg = (f'<svg xmlns="http://www.w3.org/2000/svg" width="{tile}" height="{tile}" style="flex:none"><rect width="{tile}" height="{tile}" rx="44" fill="{PALE}"/>'
           f'{mark_svg(DEEP, s, t, t)}</svg>')
    body = f'''<div style="width:1024px;height:500px;background:{BURGUNDY};display:flex;align-items:center;gap:48px;padding-left:96px;box-sizing:border-box;font-family:Lexend;color:#fff">
  {svg}
  <div><div style="font-size:84px;font-variation-settings:'wght' 540;line-height:1">Burrow</div>
  <div style="font-size:31px;font-variation-settings:'wght' 440;line-height:1.4;margin-top:22px;opacity:.92">Money that tracks itself.<br>Private. Open source.</div></div>
</div>'''
    render(page(body, 1024, 500), 1024, 500, "release/feature-graphic-1024x500.png")


def wordmark():
    """385 x 144, transparent: the rounded tile and "Burrow" in ink."""
    tile = 144
    s, t = group(tile, round(tile * 0.56))
    svg = (f'<svg xmlns="http://www.w3.org/2000/svg" width="{tile}" height="{tile}" style="flex:none"><rect width="{tile}" height="{tile}" rx="32" fill="{BURGUNDY}"/>'
           f'{mark_svg("#FFFFFF", s, t, t)}</svg>')
    body = f'''<div style="width:385px;height:144px;display:flex;align-items:center;gap:22px;font-family:Lexend;color:{INK}">
  {svg}<div style="font-size:62px;font-variation-settings:'wght' 540">Burrow</div></div>'''
    render(page(body, 385, 144), 385, 144, "design/logo/burrow-wordmark.png", transparent=True)


def icon_png(svg_text, out, size=512):
    render(page(svg_text, size, size), size, size, out, transparent=True)


D = "app/src/main/res/drawable/"


def main():
    write(D + "ic_launcher_foreground.xml", vector(108, 108, LAUNCHER_DP, "#FFFFFFFF",
          f"Launcher mark: white on the logo burgundy (ic_launcher_background), {LAUNCHER_DP} dp of the 108 dp canvas, centred."))
    write(D + "ic_launcher_monochrome.xml", vector(108, 108, LAUNCHER_DP, "#FF000000",
          "Themed-icon mark (Android 13+): the launcher mark in one colour."))
    write(D + "ic_notification.xml", vector(24, 24, 20, "#FFFFFFFF",
          "The Burrow mark, white: every notification's small icon (user, 2026-10-20), and tinted in BurrowLogo, the widget and the tile."))
    colors = os.path.join(ROOT, "app/src/main/res/values/colors.xml")
    text = open(colors).read()
    import re  # noqa: E402
    text = re.sub(r'(<color name="ic_launcher_background">)#[0-9A-Fa-f]+(</color>)', rf"\g<1>{BURGUNDY}\g<2>", text)
    open(colors, "w").write(text)
    print("app/src/main/res/values/colors.xml")

    write("design/logo/burrow-icon.svg", tile_svg(512, STORE_PX, 112, BURGUNDY, "#FFFFFF"))
    write("design/logo/burrow-icon-square.svg", tile_svg(512, STORE_PX, 0, BURGUNDY, "#FFFFFF"))
    write("design/logo/burrow-adaptive-foreground.svg", tile_svg(108, LAUNCHER_DP, 0, "none", "#FFFFFF"))
    write("design/logo/burrow-monochrome.svg", tile_svg(108, LAUNCHER_DP, 0, "none", "#000000"))
    write("design/logo/burrow-mark-white.svg", bare_svg("#FFFFFF"))
    write("design/logo/burrow-mark-burgundy.svg", bare_svg(BURGUNDY))

    icon_png(tile_svg(512, STORE_PX, 0, BURGUNDY, "#FFFFFF"), "release/icon-512.png")
    icon_png(tile_svg(512, STORE_PX, 112, BURGUNDY, "#FFFFFF"), "design/logo/burrow-icon-512.png")
    feature_graphic()
    wordmark()
    for src, dst in [("release/icon-512.png", "design/logo/play-store-icon-512.png"),
                     ("release/icon-512.png", "fastlane/metadata/android/en-US/images/icon.png"),
                     ("release/feature-graphic-1024x500.png", "design/logo/play-feature-graphic-1024x500.png"),
                     ("release/feature-graphic-1024x500.png", "fastlane/metadata/android/en-US/images/featureGraphic.png")]:
        shutil.copy(os.path.join(ROOT, src), os.path.join(ROOT, dst))
        print(dst)


if __name__ == "__main__":
    main()
